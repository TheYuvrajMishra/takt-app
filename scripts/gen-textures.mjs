// Generates two extra paper-texture tiles as PNG data URIs and writes them
// to src/theme/textures.ts. Pure Node (zlib for the PNG IDAT, hand-rolled
// CRC32) — no canvas dependency. Run: node scripts/gen-textures.mjs
//
// The three texture kinds (see PaperTexture):
//   fine   — the existing 128x128 noise tile in theme/grain.ts (cards, blocks)
//   coarse — chunky 4x4-bloc noise (buttons: BigButton, dock nodes)
//   linen  — a woven thread pattern (sheets / drawers)
// All three are black with varying alpha, so they read as a dark speckle /
// weave over any surface colour at low opacity.
import { deflateSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SIZE = 128;

// ---- CRC32 (standard table) ----------------------------------------------
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td), 0);
  return Buffer.concat([len, td, crc]);
}
function pngDataUri(pixels) {
  // pixels: Uint8Array of SIZE*SIZE*4 RGBA (black with varying alpha).
  const raw = Buffer.alloc(SIZE * (1 + SIZE * 4));
  for (let y = 0; y < SIZE; y++) {
    raw[y * (1 + SIZE * 4)] = 0; // filter: none
    raw.set(pixels.subarray(y * SIZE * 4, (y + 1) * SIZE * 4), y * (1 + SIZE * 4) + 1);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(SIZE, 0);
  ihdr.writeUInt32BE(SIZE, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // colour type RGBA
  const png = Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
  return 'data:image/png;base64,' + png.toString('base64');
}

// ---- coarse: chunky 4x4-block noise ---------------------------------------
// Noise drawn at 32x32 and upscaled 4x, so the grain reads as large soft
// blobs instead of fine speckle — visibly different from the fine tile.
function coarsePixels() {
  const low = new Uint8Array(32 * 32);
  for (let i = 0; i < low.length; i++) low[i] = Math.floor(Math.random() * 256);
  const out = new Uint8Array(SIZE * SIZE * 4);
  for (let y = 0; y < SIZE; y++) {
    for (let x = 0; x < SIZE; x++) {
      const a = low[Math.floor(y / 4) * 32 + Math.floor(x / 4)];
      const i = (y * SIZE + x) * 4;
      out[i] = 0; out[i + 1] = 0; out[i + 2] = 0; out[i + 3] = a;
    }
  }
  return out;
}

// ---- linen: woven threads --------------------------------------------------
// Horizontal + vertical threads (4px pitch) with a whisper of noise —
// reads as cloth, not speckle.
function linenPixels() {
  const out = new Uint8Array(SIZE * SIZE * 4);
  for (let y = 0; y < SIZE; y++) {
    for (let x = 0; x < SIZE; x++) {
      const hThread = (y % 4) < 2 ? 26 : 8; // horizontal thread band
      const vThread = (x % 4) < 2 ? 18 : 6; // vertical thread band
      const noise = Math.floor(Math.random() * 10);
      const a = Math.min(255, hThread + vThread + noise);
      const i = (y * SIZE + x) * 4;
      out[i] = 0; out[i + 1] = 0; out[i + 2] = 0; out[i + 3] = a;
    }
  }
  return out;
}

const coarse = pngDataUri(coarsePixels());
const linen = pngDataUri(linenPixels());

const out = `// Generated by scripts/gen-textures.mjs — do not hand-edit.
// Coarse (chunky) grain for buttons and linen weave for sheets/drawers.
// Black with varying alpha; the fine grain lives in theme/grain.ts.
export const COARSE_GRAIN_DATA_URI =\n  '${coarse}';\nexport const LINEN_DATA_URI =\n  '${linen}';\n`;
writeFileSync(join(root, 'src/theme/textures.ts'), out);
console.log('wrote src/theme/textures.ts');
console.log('coarse bytes:', Buffer.from(coarse.split(',')[1], 'base64').length);
console.log('linen bytes:', Buffer.from(linen.split(',')[1], 'base64').length);
